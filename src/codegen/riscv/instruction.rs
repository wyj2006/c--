#[derive(Debug)]
pub struct Instruction {
    pub opcode: Opcode,
    pub operands: Vec<Operand>,
}

#[derive(Debug, Clone, Copy)]
pub enum Opcode {
    Add,
    And,
    BEq,
    BEqZ,
    BitNot,
    BNeqZ,
    Call,
    Div,
    DivU,
    FAddD,
    FAddS,
    FCvtDL,
    FCvtDLU,
    FCvtDS,
    FCvtDW,
    FCvtDWU,
    FCvtLD,
    FCvtLS,
    FCvtLUD,
    FCvtLUS,
    FCvtSD,
    FCvtSL,
    FCvtSLU,
    FCvtSW,
    FCvtSWU,
    FCvtWD,
    FCvtWUD,
    FCvtWS,
    FCvtWUS,
    FDivD,
    FDivS,
    FEqD,
    FEqS,
    FLeD,
    FLeS,
    FLoadD,
    FLoadS,
    FLtD,
    FLtS,
    FMoveD,
    FMoveDL,
    FMoveDW,
    FMoveLD,
    FMoveLS,
    FMoveS,
    FMoveSL,
    FMoveSW,
    FMoveWD,
    FMoveWS,
    FMulD,
    FMulS,
    FNegD,
    FNegS,
    FStoreD,
    FStoreS,
    FSubD,
    FSubS,
    Jump,
    LoadAddr,
    LoadB,
    LoadBU,
    LoadD,
    LoadH,
    LoadHU,
    LoadImm,
    LoadW,
    LoadWU,
    LShift,
    Move,
    Mul,
    Neg,
    Or,
    Rem,
    RemU,
    Ret,
    RShiftA,
    RShiftL,
    SetEqZ,
    SetGtZ,
    SetLt,
    SetLtU,
    SetLtZ,
    SetNeqZ,
    StoreB,
    StoreH,
    StoreW,
    StoreD,
    Sub,
    Xor,
}

#[derive(Debug, Clone)]
pub enum Operand {
    Immediate(i64),
    IntReg(u64),
    FPReg(u64),
    Address { base: Box<Operand>, offset: i64 },
    Symbol(String),
}
